"""Generate the selected compiled address/backend contracts; never probe a target."""
import argparse
import html
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile


UNPROBED_STAGES = dict(source_opened="not_probed", sample_read="not_probed", layout_qualified="not_probed",
                       semantic_validation="not_probed", environment_regression="not_performed")


def decode_inventory(text):
    def unique(pairs):
        result = dict(pairs)
        if len(result) != len(pairs):
            raise ValueError("duplicate inventory field")
        return result

    return json.loads(text, object_pairs_hook=unique)


def public_text(value):
    if not isinstance(value, str) or not value or not value.isprintable():
        raise ValueError("invalid capability cell")
    escaped = html.escape(value, quote=False).replace("\\", "\\\\")
    for mark in ("|", "`", "[", "]", "*"):
        escaped = escaped.replace(mark, "\\" + mark)
    return escaped


def probe_catalog(data):
    if "probe_contracts" not in data:
        return None
    contracts = data["probe_contracts"]
    if not isinstance(contracts, list):
        raise ValueError("invalid compiled probe catalog")
    rows, selectors = {}, {}
    for contract in contracts:
        if not isinstance(contract, dict) or set(contract) != {"id", "invocation", "availability_scope", "observation"}:
            raise ValueError("unexpected compiled probe contract")
        name, command, scope = contract["id"], contract["invocation"], contract["availability_scope"]
        if (not all(isinstance(value, str) for value in (name, command, scope)) or name in rows or
                not all(re.fullmatch(r"[a-z][a-z0-9_]*", value) for value in (name, scope)) or
                not re.fullmatch(r"--capabilities --[a-z][a-z0-9-]*(?: [A-Za-z0-9_<>\[\].-]+)*", command)):
            raise ValueError("invalid probe identifier or invocation")
        selector = command.split()[1]
        if selectors.setdefault(selector, command) != command:
            raise ValueError("conflicting syntax for the same probe selector")
        observation = public_text(contract["observation"])
        rows[name] = f"| `{name}` | `{command}` | `{scope}` | {observation} |"
    return rows


def render(data):
    if (not isinstance(data, dict) or data.get("schema") != "kn.capabilities.v1" or
            data.get("target_probed") is not False or data.get("scope") != "compiled_contract" or "probe" in data or
            data.get("inventory_complete") is not False):
        raise ValueError("only the unprobed compiled contract can generate public documentation")
    target = data.get("target")
    if target is not None and target != dict(os_build=None, security_state="unknown", virtual_address_bits=None, validation="not_performed"):
        raise ValueError("target-specific metadata cannot generate a public matrix")
    catalog = probe_catalog(data)
    if catalog is not None and target is None:
        raise ValueError("cataloged inventory requires an unprobed target descriptor")
    lines = [
        "# Selected source support contracts", "",
        "Generated by `tools/generate-support-matrix.py` from `--capabilities`.",
        "Each row describes an operation compiled into the binary. Platform validation",
        "requires separate evidence about the target, source, layout and test run.", "",
    ]
    if catalog is None:
        lines += ["This binary does not declare its probe catalog.", ""]
    elif catalog:
        lines += ["## Standalone probe contracts", "",
                  "The command syntax and scope come from the executable. Contracts can share",
                  "one invocation when it collects more than one observation.", "",
                  "| Contract | Invocation | Availability scope | Observation |",
                  "| --- | --- | --- | --- |", *catalog.values(), ""]
    else:
        lines += ["The binary declares an empty probe catalog.", ""]
    lines += [
        "## Address and backend contracts", "",
        "Address shape alone cannot establish mapping, effective permissions,",
        "decoder coverage or compatibility with a real LA57 target. `legacy_la48`",
        "identifies a recorded compatibility assumption. WOW64 pointer slots, VTL1",
        "and hardware execution backends require independent qualification.", "",
    ]
    title = "| Domain / operation | Backend | Implementation | Address contract | Consistency |"
    separator = "| --- | --- | --- | --- | --- |"
    if catalog is not None:
        lines += ["A dash means the binary declares no standalone probe for that operation.", ""]
    lines += [title + (" Probe contract |" if catalog is not None else ""),
              separator + (" --- |" if catalog is not None else "")]
    seen, used = set(), set()
    for item in data["capabilities"]:
        if not isinstance(item, dict):
            raise ValueError("invalid capability row")
        if catalog is not None and not {"availability_scope", "validation", "probe_stages", "probe_contract"} <= item.keys():
            raise ValueError("incomplete cataloged capability")
        key = (item["domain"], item["operation"], item["backend"])
        if (not all(isinstance(value, str) and value for value in key) or key in seen or
                item.get("availability") != "not_probed" or item.get("availability_scope", "none") != "none" or
                item.get("validation", "not_performed_for_target_environment") != "not_performed_for_target_environment" or
                item.get("probe_stages", UNPROBED_STAGES) != UNPROBED_STAGES or
                "range_evidence" in item or "record_evidence" in item):
            raise ValueError("duplicate or probed capability")
        seen.add(key)
        cells = [public_text(cell) for cell in (f"{key[0]} / {key[1]}", key[2], item["implementation"],
                                                item["address_contract"], item["consistency"])]
        if catalog is not None:
            route = item["probe_contract"]
            if route is not None:
                if not isinstance(route, str) or route not in catalog or item["implementation"] == "unsupported":
                    raise ValueError("capability references an unavailable probe contract")
                used.add(route)
            cells.append(f"`{route}`" if route is not None else "—")
        elif "probe_contract" in item:
            raise ValueError("probe reference without a catalog")
        lines.append("| " + " | ".join(cells) + " |")
    if not seen or (catalog is not None and used != set(catalog)):
        raise ValueError("empty inventory or unreferenced probe contract")
    lines += ["", "The JSON contract also lists each operation's requirements and limits.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exe", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "docs/SUPPORT_MATRIX.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        run = subprocess.run([str(args.exe.resolve()), "--capabilities"], check=True,
                             capture_output=True, text=True, encoding="utf-8", timeout=30)
        content = render(decode_inventory(run.stdout))
        if args.check:
            if args.output.read_text(encoding="utf-8-sig") != content:
                raise ValueError("generated support matrix is stale")
        else:
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                                 dir=args.output.parent, prefix=".support-matrix-",
                                                 delete=False) as stream:
                    temporary = Path(stream.name)
                    stream.write(content)
                    stream.flush()
                    os.fsync(stream.fileno())
                os.replace(temporary, args.output)
                temporary = None
            finally:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError):
        print("Support matrix validation/generation failed; check the compiled contract and output.")
        return 1
    print("Support matrix matches compiled contracts" if args.check else "Support matrix generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
